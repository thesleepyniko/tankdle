<script lang="ts">
	import { resolve } from '$app/paths'
    import { page } from '$app/state';
    import type { PageProps } from './$types';
    import { enhance, type SubmitFunction } from '$app/forms'
    import { goto } from '$app/navigation'

    type GuessResult = {
        name: string,
        correct: boolean,
        class: {value: string, match: boolean},
        role: {value: string, match: boolean},
        team: {value: string, match: boolean}
    }
    type Reveal = {name: string; team: string; role: string;}
    type GuessResponse = { result: GuessResult; answer: Reveal | null }

    let guesses = $state<GuessResult[]>([])
    let answer = $state<Reveal | null>(null)
    let finished = $derived(answer !== null)

    const submitGuess: SubmitFunction<GuessResponse, { message: string }> = () => {
        return async ({ result, update }) => {
            if (result.type === 'success' && result.data) {
                guesses.push(result.data.result)
                answer = result.data.answer
                query = ''
            }

            await update({ reset: false, invalidateAll: false })
        }
    }

    async function generateResults() {
        let temp = 'MTCdle ' + (type === 'infinite' ? 'infinite' : new Date().toISOString().slice(0, 10))
        temp += ' ' + (guesses.at(-1)?.correct ? `${guesses.length}/5` : 'X/5') + '\n'
        for (const guess of guesses) {
            temp += guess.class.match ? '🟩' : '⬛'
            temp += guess.role.match ? '🟩' : '⬛'
            temp += guess.team.match ? '🟩' : '⬛'
            temp += '\n'
        }
        await navigator.clipboard.writeText(temp);
    }

    let { data, form }: PageProps = $props()
    let type = $derived(page.url.searchParams.get('type') ?? '');
    let query = $state('');
    

    // BEGIN: GENERATED BY CLAUDE
    $effect(() => {
        void data.identifier
        guesses = []
        answer = null
    })
    // END: GENERATED BY CLAUDE


    let slugByName = $derived(
        Object.fromEntries(Object.entries(data.vehicles).map(([slug, name]) => [name, slug]))
    )
    let guessSlug = $derived(slugByName[query] ?? '')
</script>

<div class="game">
    
    {#if type === "infinite"}
        <h1 aria-label="MTCdle">
            <svg aria-hidden="true" class="mtc-logo" viewBox="0 0 1000 360"><g fill="currentColor"><path d="m198 157.4l40.4-155.6h157.5v356.4h-126.6v-166.5l-38.5 166.5h-65.7l-38.5-166.5v166.5h-126.6v-356.4h157.5z"></path><path d="m681 2.3v75.6h-66.6v279.8h-134.3v-279.8h-66.6v-75.6z"></path><path d="m695.5 57l86.1-56.2h133.2l85.2 56.2v90h-134.2v-66.7h-32.8v203.2h33.8v-82.8h133.2v107.5l-81.8 51h-132.8l-89.9-51z"></path></g></svg>dle<span class="subtitle">infinite</span>
        </h1>
        <img class="tank" alt="Mystery tank to guess" src={resolve('/infinite/[identifier]', { identifier: data.identifier })}>
        <form method="POST" action="?type=infinite&/guess" use:enhance={submitGuess}>            <label for="guess">Guess a tank:</label>
            <input list="vehicle-options" bind:value={query} disabled={finished} />
            <datalist id="vehicle-options">
                {#each Object.entries(data.vehicles) as [slug, name] (slug)}
                    <option value={name} data-slug={slug}></option>
                {/each}
            </datalist>
            <input type="hidden" id="guess" name="guess" value={guessSlug} />
            <input type="hidden" name="identifier" value={data.identifier} />
            <input type="hidden" name="guessNumber" value={guesses.length + 1} />
            <button disabled={!guessSlug || finished}>Guess</button>
        </form>
<!--  -->
    {:else}
        <h1 aria-label="MTCdle">
            <svg aria-hidden="true" class="mtc-logo" viewBox="0 0 1000 360"><g fill="currentColor"><path d="m198 157.4l40.4-155.6h157.5v356.4h-126.6v-166.5l-38.5 166.5h-65.7l-38.5-166.5v166.5h-126.6v-356.4h157.5z"></path><path d="m681 2.3v75.6h-66.6v279.8h-134.3v-279.8h-66.6v-75.6z"></path><path d="m695.5 57l86.1-56.2h133.2l85.2 56.2v90h-134.2v-66.7h-32.8v203.2h33.8v-82.8h133.2v107.5l-81.8 51h-132.8l-89.9-51z"></path></g></svg>dle<span class="subtitle">daily</span>
        </h1>
        <img class="tank" alt="Mystery tank to guess" src={resolve('/daily')}>
        <form method="POST" action="?/guess" use:enhance={submitGuess}>
            <label for="guess">Guess a tank:</label>
            <input list="vehicle-options" bind:value={query} disabled={finished} />
            <datalist id="vehicle-options">
                {#each Object.entries(data.vehicles) as [slug, name] (slug)}
                    <option value={name} data-slug={slug}></option>
                {/each}
            </datalist>
            <input type="hidden" id="guess" name="guess" value={guessSlug}/>
            <input type="hidden" name="identifier" value={data.identifier} />
            <input type="hidden" name="guessNumber" value={guesses.length + 1} />
            <button disabled={!guessSlug || finished}>Guess</button>
        </form>
    {/if}

    <!-- BEGIN: GENERATED BY CLAUDE -->
    {#if form?.message}
        <p>{form.message}</p>
    {/if}

    {#if guesses.length}
        <table>
            <thead>
                <tr><th>Vehicle</th><th>Class</th><th>Role</th><th>Team</th></tr>
            </thead>
            <tbody>
                {#each guesses as g, i (i)}
                    <tr>
                        <td class="name" class:correct={g.correct}>{g.name}</td>
                        <td class="hint" class:match={g.class.match}>
                            <span aria-hidden="true">{g.class.match ? '✓' : '✗'}</span> {g.class.value}
                        </td>
                        <td class="hint" class:match={g.role.match}>
                            <span aria-hidden="true">{g.role.match ? '✓' : '✗'}</span> {g.role.value}
                        </td>
                        <td class="hint" class:match={g.team.match}>
                            <span aria-hidden="true">{g.team.match ? '✓' : '✗'}</span> {g.team.value}
                        </td>
                    </tr>
                {/each}
            </tbody>
        </table>
    {/if}

    {#if answer}
        <p>{guesses.at(-1)?.correct ? 'You got it!' : 'Out of guesses.'} It was the {answer.name}.</p>
        {#if !(type === "infinite")} 
            <!-- eslint-disable-next-line svelte/no-navigation-without-resolve -->
            <button onclick={() => goto(resolve('/play') + '?type=infinite', { invalidateAll: true })}>
                Begin infinite mode
            </button>
        {:else}
            <!-- eslint-disable-next-line svelte/no-navigation-without-resolve -->
            <button onclick={() => goto(resolve('/play') + '?type=infinite', { invalidateAll: true })}>
                Play Again
            </button>
        {/if}
        <button type="button" disabled={!finished} onclick={() => generateResults()}>Copy results</button>
    {/if}
    <!-- END: GENERATED BY CLAUDE -->
</div>

